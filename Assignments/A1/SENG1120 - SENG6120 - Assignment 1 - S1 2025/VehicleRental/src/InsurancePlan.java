/**
 * An interface representing an insurance plan.
 * This interface is primarily used to specify the daily rate of an insurance plan.
 * 
 * @author Kyle Robert Harrison
 * @version 1.0, 13 March 2025
 */
public interface InsurancePlan {
    /**
     * Returns the daily rate of the insurance plan.
     * 
     * @return The daily rate of the insurance plan
     */
    double getDailyRate();
}